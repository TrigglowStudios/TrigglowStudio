export type MsgKey = keyof (typeof DICT)['en'];
export type { AppLocale };

let localePrefs: LocalePrefs = { locale: null, localePending: false };
let accountLocale: AppLocale | null = null;

/** Main keeps these current: the language saved in config.json, and the signed-in account's (null when signed out). */
export function setLocaleSources(src: { prefs?: LocalePrefs; account?: AppLocale | null }): void {
  if (src.prefs) localePrefs = { locale: src.prefs.locale, localePending: src.prefs.localePending };
  if (src.account !== undefined) accountLocale = src.account;
}

/**
 * The app's language (en, es, pt-BR, zh, fr, it, de, ru, ko, ja, hi, ca, uk, ca-valencia, eu, gl): the user's pick beats the OS (see pickLocale). Used for the tray,
 * native notifications, OBS text sources, the bundled screens and the local chat dock (GET /api/locale).
 */
export function appLocale(): AppLocale {
  return pickLocale(localePrefs, accountLocale, app.getLocale());
}

/** Text for native notifications (the bundled screens have their own dictionary in assets/i18n.js). */
export function nt(key: MsgKey, vars: Record<string, string> = {}): string {
  const lang = appLocale();
  return (DICT[lang]?.[key] ?? DICT.en[key]).replace(/\{(\w+)\}/g, (_, k: string) => vars[k] ?? '');
}
